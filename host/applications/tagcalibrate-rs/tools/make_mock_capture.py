#!/usr/bin/env python3
"""Build ui/mock-capture.js, the replay data of Tag Calibrator's mock engine.

    make_mock_capture.py <capture-fixture.json> <replay.log> [out.js]

Joins a qtcalibrate sample capture (raw magnetometer and accelerometer
samples, fitted calibration) with the angles qtcalibrate itself computed for
each sample while replaying it, so the mock shows the app's own eCompass
results rather than a reimplementation. The page itself
computes none of them; in the app they come from the engine.

The angles come from a replay log: qtcalibrate logs each sample's angles at
trace level, below what --log-file records. For one run, change that line in
MainWindow::processCalibrationSample() (mainwindow.cpp) to

    log_debug("Pitch: %.2f Roll %.2f Yaw %.2f Heading %.2f Dip %.2f Field %.2f",
              pitch, roll, yaw, angles.yaw, dip, field);

rebuild, run

    qtcalibrate --replay-capture <fixture> --log-file replay.log --replay-exit --no-auto-attach

then revert the change. Each sample row in mock-capture.js is
mx, my, mz, ax, ay, az, pitch, roll, model yaw, heading, dip, field.
"""

import json
import re
import sys
from datetime import datetime


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    fixture, log = sys.argv[1], sys.argv[2]
    out = sys.argv[3] if len(sys.argv) > 3 else "mock-capture.js"
    d = json.load(open(fixture))
    pattern = r"Pitch: (\S+) Roll (\S+) Yaw (\S+) Heading (\S+) Dip (\S+) Field (\S+)"
    angles = [tuple(float(x) for x in m.groups()) for m in re.finditer(pattern, open(log).read())]
    if len(angles) != len(d["samples"]):
        sys.exit(f"{len(angles)} angle lines for {len(d['samples'])} samples")
    t0 = datetime.fromisoformat(d["capture_started_utc"].replace("Z", "+00:00"))
    t1 = datetime.fromisoformat(d["capture_stopped_utc"].replace("Z", "+00:00"))
    data = {
        "source": "host/docs/fixtures/qtcalibrate/" + fixture.rsplit("/", 1)[-1],
        "angles_from": "qtcalibrate --replay-capture of that file (its own eCompass; "
                       "pitch, roll, model yaw, heading, dip, field per sample)",
        "duration_s": round((t1 - t0).total_seconds(), 1),
        "calibration": {k: d["calibration"][k] for k in ("field", "mapping", "offset")},
        "columns": ["mx", "my", "mz", "ax", "ay", "az", "pitch", "roll", "model_yaw",
                    "heading", "dip", "field"],
        "samples": [
            [round(s["mag"]["mx"], 3), round(s["mag"]["my"], 3), round(s["mag"]["mz"], 3),
             round(s["accel"]["ax"], 2), round(s["accel"]["ay"], 2), round(s["accel"]["az"], 2),
             *a]
            for s, a in zip(d["samples"], angles)
        ],
    }
    with open(out, "w") as f:
        f.write("// The mock engine's replay data: a qtcalibrate capture fixture joined with the angles\n"
                "// qtcalibrate computed for each sample. Generated by ../tools/make_mock_capture.py.\n"
                "window.CAPTURE = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    print(f"{out}: {len(data['samples'])} samples")
    return 0


if __name__ == "__main__":
    sys.exit(main())
