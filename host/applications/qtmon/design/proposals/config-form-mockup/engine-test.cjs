// Checks the mock engine's rules: node engine-test.cjs (from this directory).
globalThis.window = globalThis;
require('./spec.js'); require('./engine.js');
const e = new MockEngine(); let id = 1;
const call = (c, v) => e.handle({ id: id++, cmd: { case: c, value: v } });
const st = (evs) => evs.find((x) => x.ev.case === 'formState').ev.value;
const ok = (cond, msg) => { console.log((cond ? 'ok  ' : 'FAIL') + ' ' + msg); if (!cond) process.exitCode = 1; };

let s = st(call('loadDefaults', { tagType: 'BITTAG' }));
ok(JSON.stringify(s.config) === JSON.stringify(e.config()) && !s.modified, 'defaults load unmodified');
ok(s.config.adxl362.range === 'R4G' && s.config.bittag_log === 'BITTAG_BITSPERFIVEMIN', 'BITTAG defaults round-trip');
s = st(call('setField', { panel: 'Adxl362Standard', field: 'act_thresh_g', value: 1.906 }));
ok(s.values['Adxl362Standard.act_thresh_g'] === 1.91, 'threshold rounded to 2 decimals, as the spin box does: ' + s.values['Adxl362Standard.act_thresh_g']);
s = st(call('setField', { panel: 'Adxl362Standard', field: 'act_thresh_g', value: 9 }));
ok(s.values['Adxl362Standard.act_thresh_g'] === 2, 'threshold clamped to the 4 g range maximum (2 g)');
s = st(call('setField', { panel: 'Adxl362Standard', field: 'range', value: 'R2G' }));
ok(s.values['Adxl362Standard.act_thresh_g'] === 1 && s.modified, 'range 2g re-clamps threshold to 1 g');
s = st(call('setField', { panel: 'Adxl362Standard', field: 'freq', value: 'S400' }));
ok(Math.abs(s.constraints['Adxl362Standard.inactive_sec'].max - 255/400) < 1e-9 && s.values['Adxl362Standard.inactive_sec'] <= 255/400, 'rate 400 Hz limits inactivity to 255/400 s');
const t = Math.floor(Date.now()/1000) + 5*86400 + 1234;
s = st(call('setField', { panel: 'IntervalSchedule', field: 'start', value: { mode: 'at', epoch: t } }));
ok(s.values['IntervalSchedule.start'].epoch % 3600 === 0 && s.values['IntervalSchedule.start'].epoch >= t, 'start rounded up to the hour');
ok(s.config.active_interval.start_epoch === s.values['IntervalSchedule.start'].epoch, 'start written to active_interval');
s = st(call('setField', { panel: 'IntervalSchedule', field: 'end', value: { mode: 'at', epoch: t - 86400 } }));
ok(!!s.errors['IntervalSchedule.end'], 'end before start is an error: ' + s.errors['IntervalSchedule.end']);
s = st(call('setField', { panel: 'IntervalSchedule', field: 'hibernate', value: [{ inUse: true, start: 0, end: 0 }, { inUse: false, start: 0, end: 0 }] }));
const h = s.values['IntervalSchedule.hibernate'][0];
ok(h.start === s.values['IntervalSchedule.start'].epoch && h.end === h.start + 3600, 'new hibernation row starts at the logging start, lasts an hour');
ok(s.config.hibernate[1].start_epoch === 0 && s.config.hibernate[1].end_epoch === 0, 'unused row sent as 0 to 0');
let r = call('start', { anyway: false });
ok(r[0].ev.case === 'startChecks' && r[0].ev.value.failures.length >= 2, 'start refused with failures: ' + JSON.stringify(r[0].ev.value.failures));
call('setTagStatus', { approved: true });
call('setField', { panel: 'IntervalSchedule', field: 'end', value: { mode: 'never', epoch: 0 } });
r = call('start', { anyway: false });
ok(r[0].ev.case === 'started', 'start accepted once checks pass');
s = st(call('readFromTag', {}));
ok(s.source === 'Tag' && !s.editable, 'tag running: its configuration is read-only');
r = call('setField', { panel: 'Adxl362Standard', field: 'range', value: 'R8G' });
ok(r[0].ev.case === 'error', 'edit refused while running: ' + r[0].ev.value.message);
s = st(call('openConfig', { path: 'x.json', text: JSON.stringify({ tag_type: 'PRESTAG', period: 120 }) }));
ok(s.tagType === 'PRESTAG' && s.config.period === 120 && s.config.hibernate.length === 2, 'file merged onto its type defaults');
s = st(call('setField', { panel: 'IntervalScheduleWithPeriod', field: 'period', value: 1000 }));
ok(s.values['IntervalScheduleWithPeriod.period'] === 300, 'period clamped to 300');
s = st(call('loadDefaults', { tagType: 'IMUTAG' }));
ok(s.config.start_delay === 1 && s.values['StartDelaySchedule.start_delay'] === 0, 'IMUTag start_delay stored as minutes + 1');
s = st(call('loadDefaults', { tagType: 'BITTAGNG' }));
ok(s.config.adxl362.accel_type === 'AdxlType_367', 'accel_type passes through untouched');
